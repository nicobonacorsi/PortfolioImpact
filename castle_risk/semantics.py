"""Conservative, deterministic verification of event-to-contract semantics.

Relationship orientation is ALWAYS X = market and Y = target. Text generated by
an LLM is a proposal, never a source of certified predicates. Certification here
means a supported parser/identity check passed, conditional on source accuracy;
it is not a legal opinion about exchange settlement.
"""
from __future__ import annotations

from datetime import datetime
from decimal import Decimal, InvalidOperation
import hashlib
import json
import re
from typing import Any, Mapping

RELATIONSHIPS = frozenset({"EQUIVALENT", "IMPLIES", "IMPLIED_BY", "EXCLUDES", "NONE"})
OPERATORS = frozenset({"gt", "ge", "lt", "le", "eq"})
CONTEXT_FIELDS = ("metric", "source", "period", "vintage", "unit", "cancellation_policy")
FED_SECONDARY = ('This market is mutually exclusive. Therefore, if the Federal Reserve hikes by 50bps, '
                 'the 50bps market will resolve to Yes and the 25bps market will resolve to No. '
                 'Only one bucket, at maximum, can resolve to Yes. Note 4/28/25: For the markets beginning '
                 'after the May meeting, if a scheduled FOMC meeting is canceled and does not occur on '
                 'its scheduled date, then the strike for "Fed maintains rate" will resolve to Yes '
                 'and all others will resolve to No.')
FED_PRIMARY_RE = re.compile(
    r"If the Federal Reserve does a (Hike|Cut) of\s+(>?)([0-9]+(?:\.[0-9]+)?)bps on "
    r"([A-Z][a-z]+ [0-9]{1,2}, [0-9]{4}), then the market resolves to Yes\.")

# A deliberately narrow reviewed case. The API summary and terms disagree about
# exceptional expiration timing. No parser may silently choose which overrides.
CPI_TERMS_SHA256 = "2cdb3a94c1419e18d0652c47133dd82284a2c153366a7603c03ac0370daf57e6"
CPI_MODEL_ASSUMPTIONS = (
    "All selected KXCPI-26OCT strikes use one common scalar expiration value and the same final determination time.",
    "The displayed strict-threshold payout criterion applies without a contract-specific discretionary override or nonbinary payout.",
    "The unresolved API-versus-PDF exceptional-expiration provisions are represented by a common convention; no precedence is asserted.",
)
CPI_PRIMARY_RE = re.compile(
    r"If the Consumer Price Index \(CPI\) increases by more than (-?[0-9]+(?:\.[0-9]+)?)% "
    r"\(single-decimal\) in October 2026, then the market resolves to Yes\.")
CPI_SECONDARY = (
    "The market will always close at 8:29 AM ET on the scheduled day of the data release "
    "(November 10, 2026). Please note: the Expiration Value is the single-decimal value "
    "published at the Source Agency. In the case of a delay in data caused by a federal "
    "government shutdown impacting the reliability of the Source Agency, the market’s "
    "latest Expiration Date will be extended to the sooner of the release of the Underlying "
    "or six months after the end of the government shutdown."
)


class SemanticValidationError(ValueError):
    """Malformed or unsupported structured semantic input."""


def _number(value: Any) -> Decimal:
    if isinstance(value, bool):
        raise SemanticValidationError("Boolean values are not thresholds.")
    try:
        result = Decimal(str(value))
    except (InvalidOperation, ValueError):
        raise SemanticValidationError("Threshold must be numeric.") from None
    if not result.is_finite():
        raise SemanticValidationError("Threshold must be finite.")
    return result


def validate_predicate(predicate: Mapping[str, Any]) -> dict[str, Any]:
    if not isinstance(predicate, Mapping):
        raise SemanticValidationError("Predicate must be an object.")
    result = dict(predicate)
    for key in CONTEXT_FIELDS[:-1]:
        if not isinstance(result.get(key), str) or not result[key].strip():
            raise SemanticValidationError(f"Missing predicate context: {key}.")
    if result.get("operator") not in OPERATORS:
        raise SemanticValidationError("Unsupported threshold operator.")
    _number(result.get("threshold"))
    result.setdefault("cancellation_policy", "not_applicable")
    if not isinstance(result["cancellation_policy"], str):
        raise SemanticValidationError("Cancellation policy must be a string.")
    return result


def _interval(predicate: Mapping[str, Any]) -> tuple[Decimal, bool, Decimal, bool]:
    a = _number(predicate["threshold"])
    infinity = Decimal("Infinity")
    return {
        "gt": (a, False, infinity, False), "ge": (a, True, infinity, False),
        "lt": (-infinity, False, a, False), "le": (-infinity, False, a, True),
        "eq": (a, True, a, True),
    }[predicate["operator"]]


def _subset(left: tuple, right: tuple) -> bool:
    a, ai, b, bi = left
    c, ci, d, di = right
    return (a > c or (a == c and (not ai or ci))) and (b < d or (b == d and (not bi or di)))


def _disjoint(left: tuple, right: tuple) -> bool:
    a, ai, b, bi = left
    c, ci, d, di = right
    return b < c or d < a or (b == c and not (bi and ci)) or (d == a and not (di and ai))


def deterministic_relation(target_predicate: Mapping[str, Any], market_predicate: Mapping[str, Any]) -> str:
    """Infer an exact scalar-set relation, never assuming quantized outcomes.

    Different measurement dates, sources, units, vintages or cancellation policies
    are incomparable. A threshold of 25bp is not silently rounded to 50bp.
    """
    target, market = validate_predicate(target_predicate), validate_predicate(market_predicate)
    if any(target[key] != market[key] for key in CONTEXT_FIELDS):
        return "NONE"
    y, x = _interval(target), _interval(market)
    if x == y:
        return "EQUIVALENT"
    if _subset(x, y):
        return "IMPLIES"
    if _subset(y, x):
        return "IMPLIED_BY"
    if _disjoint(x, y):
        return "EXCLUDES"
    return "NONE"


def resolution_rules(market: Mapping[str, Any]) -> str:
    primary = market.get("rules_primary", "")
    secondary = market.get("rules_secondary", "")
    if not primary and isinstance(market.get("raw"), Mapping):
        return resolution_rules(market["raw"])
    if primary or secondary:
        return "\n".join(str(t) for t in (primary, secondary) if t)
    return str(market.get("resolution_rules", market.get("rules", "")))


def market_identifier(market: Mapping[str, Any]) -> str:
    return str(market.get("market_id", market.get("ticker", "")))


def make_contract_target(market: Mapping[str, Any]) -> dict[str, Any]:
    """Explicitly define Y as THIS contract settling YES, including all its rules."""
    rules = resolution_rules(market)
    identifier = market_identifier(market)
    if not identifier or not rules:
        raise SemanticValidationError("A contract target needs an identifier and actual resolution rules.")
    return {
        "event_id": "target-" + identifier,
        "title": str(market.get("title", identifier)),
        "description": f"The Kalshi contract {identifier} settles YES under the displayed rules, including cancellation provisions.",
        "contract_id": identifier, "venue": market.get("venue", "kalshi"),
        "rules_sha256": hashlib.sha256(rules.encode()).hexdigest(),
        "definition_origin": "CONTRACT_IDENTITY", "resolution_rules": rules,
    }


def make_fed_target(meeting_date: str, operator: str = "le", threshold: float = -25) -> dict[str, Any]:
    """A user-defined rate-change event; canceled meetings are assigned zero change.

    This is a precise contract-compatible event, not an unrestricted event such
    as any emergency cut before the date. The cancellation convention is explicit.
    """
    datetime.strptime(meeting_date, "%Y-%m-%d")
    p = {
        "metric": "fed_target_rate_change", "source": "Federal Reserve", "period": meeting_date,
        "vintage": "scheduled_meeting_decision", "unit": "basis_points", "operator": operator,
        "threshold": threshold, "cancellation_policy": "no_change",
    }
    validate_predicate(p)
    symbol = {"le": "<=", "lt": "<", "ge": ">=", "gt": ">", "eq": "="}[operator]
    description = (f"Federal Reserve rate change {symbol} {threshold:g} basis points at the scheduled "
                   f"{meeting_date} meeting; a canceled meeting counts as zero change.")
    return {"event_id": f"fed-{meeting_date}-{operator}-{threshold}", "title": description,
            "description": description, "event_date": meeting_date, "predicate": p,
            "definition_origin": "USER_DEFINED"}


def parse_kalshi_fed_market(market: Mapping[str, Any]) -> dict[str, Any]:
    """Recognize the retrieved KXFEDDECISION template and cross-check its metadata.

    This parser fails closed on any additional/changed secondary provision.
    It deliberately rejects observed >25 contracts whose primary rules omit >.
    Source identity is supplied by the trusted adapter, never by the LLM output.
    """
    metadata = market.get("metadata", {})
    raw = market.get("raw", metadata.get("raw", market) if isinstance(metadata, Mapping) else market)
    if not isinstance(raw, Mapping):
        return {"status": "UNVERIFIED", "reason": "Missing raw market object."}
    def reject(reason: str) -> dict:
        return {"status": "UNVERIFIED", "reason": reason, "predicate": None}
    if str(market.get("venue", "kalshi")).lower() != "kalshi":
        return reject("Unsupported venue; cross-venue identity is not assumed.")
    ticker = raw.get("ticker", market_identifier(market))
    if not str(ticker).startswith("KXFEDDECISION-"):
        return reject("No supported deterministic parser for this contract family.")
    primary, secondary = raw.get("rules_primary", ""), raw.get("rules_secondary", "")
    if not isinstance(primary, str) or not isinstance(secondary, str):
        return reject("Resolution rules must be strings.")
    match = FED_PRIMARY_RE.fullmatch(primary)
    if not match:
        return reject("Primary rule does not match the reviewed complete template.")
    if " ".join(secondary.split()) != " ".join(FED_SECONDARY.split()):
        return reject("Secondary rules changed or are missing; cancellation semantics unverified.")
    action, modifier, magnitude, date_text = match.groups()
    try:
        day = datetime.strptime(date_text, "%B %d, %Y").date()
    except ValueError:
        return reject("Invalid meeting date in primary rule.")
    if day.isoformat() < "2025-06-01":
        return reject("Cancellation-policy version predates the supported template.")
    custom_strike = raw.get("custom_strike")
    if not isinstance(custom_strike, Mapping) or dict(custom_strike) != {action: modifier + magnitude}:
        return reject("Primary rule conflicts with structured strike metadata; no silent repair.")
    subtitle = str(raw.get("yes_sub_title", raw.get("subtitle", "")))
    expected = f"{action} {modifier}{magnitude}bps"
    if not (subtitle == expected or (action == "Hike" and magnitude == "0" and not modifier and subtitle == "Fed maintains rate")):
        return reject("Primary rule conflicts with the YES contract label.")
    if modifier not in {"", ">"}:
        return reject("Unsupported comparator.")
    exact_amount = _number(magnitude)
    if exact_amount > 1000000:
        return reject("Rate-change magnitude exceeds the supported parser domain.")
    amount = float(exact_amount)
    if action == "Cut" and amount == 0:
        return reject("Zero cut template is not reviewed.")
    sign = 1 if action == "Hike" else -1
    operator = ("gt" if action == "Hike" else "lt") if modifier else "eq"
    p = make_fed_target(day.isoformat(), operator, sign * amount)["predicate"]
    return {"status": "CERTIFIED", "predicate": p, "parser": "kalshi_fed_v1",
            "evidence": [primary, secondary],
            "reason": "Complete reviewed primary and secondary templates match; strike and label agree. Conditional on accurate exchange data."}


def make_cpi_settlement_target(period: str = "2026-10", operator: str = "ge",
                               threshold: float = 0.35) -> dict[str, Any]:
    """Define a nonidentity settlement-value event, with explicit model conditions.

    This does NOT redefine a user's ordinary BLS first-release question. The
    separate named example explicitly adopts the common settlement-value model.
    No lattice assumption is made: the PDF has a nonpublication fallback whose
    numerical interpretation is not established by this application.
    """
    if period != "2026-10":
        raise SemanticValidationError("Only the reviewed October 2026 CPI case is supported.")
    p = {
        "metric": "kalshi_headline_cpi_u_sa_mom_common_expiration_value",
        "source": "Bureau of Labor Statistics; Kalshi CPI settlement terms",
        "period": period, "vintage": "value_at_common_expiration_including_documented_fallback",
        "unit": "percent", "operator": operator, "threshold": threshold,
        "cancellation_policy": "common_resolution_model:sha256:" + CPI_TERMS_SHA256,
    }
    validate_predicate(p)
    symbol = {"le": "<=", "lt": "<", "ge": ">=", "gt": ">", "eq": "="}[operator]
    description = (
        f"October 2026 common Kalshi CPI settlement reference value {symbol} {threshold:g}%; "
        "includes the venue's common fallback value when applicable, under the displayed "
        "common-resolution assumptions. This is not the unrestricted first BLS release event."
    )
    return {
        "event_id": f"cpi-settlement-{period}-{operator}-{threshold}", "title": description,
        "description": description, "event_date": "2026-11-10", "predicate": p,
        "definition_origin": "USER_DEFINED", "definition_scope": "NONIDENTITY_SETTLEMENT_RULE_DEFINED",
        "accepted_model_assumptions": list(CPI_MODEL_ASSUMPTIONS),
        "required_model_assumptions": list(CPI_MODEL_ASSUMPTIONS),
    }


def parse_kalshi_cpi_market(market: Mapping[str, Any]) -> dict[str, Any]:
    """Parse the reviewed October CPI case under explicit shared-value assumptions.

    The trusted loader supplies parent event/series and a hash-verified terms
    reference. Model-produced predicates, labels, or copies of its own assertions
    are never used as certification evidence. Missing/changed context fails closed.
    """
    metadata = market.get("metadata", {})
    raw = market.get("raw", metadata.get("raw", market) if isinstance(metadata, Mapping) else market)
    def reject(reason: str) -> dict:
        return {"status": "UNVERIFIED", "reason": reason, "predicate": None}
    if not isinstance(raw, Mapping) or str(market.get("venue", "kalshi")).lower() != "kalshi":
        return reject("Missing Kalshi raw record or unsupported venue.")
    context = raw.get("_reviewed_context", market.get("_reviewed_context", {}))
    if not isinstance(context, Mapping):
        return reject("Missing independently archived event, series and terms context.")
    event, series = context.get("event", {}), context.get("series", {})
    if not isinstance(event, Mapping) or not isinstance(series, Mapping):
        return reject("Invalid parent event or series context.")
    source = [{"name": "Bureau of Labor Statistics", "url": "https://www.bls.gov/cpi/"}]
    if (event.get("event_ticker") != "KXCPI-26OCT" or event.get("series_ticker") != "KXCPI"
            or raw.get("event_ticker") != event.get("event_ticker")
            or event.get("mutually_exclusive") is not False
            or event.get("settlement_sources") != source or series.get("settlement_sources") != source
            or series.get("ticker") != "KXCPI"
            or series.get("contract_terms_url") != "https://assets.kalshi.com/contract_terms/CPI.pdf"
            or context.get("terms_sha256") != CPI_TERMS_SHA256):
        return reject("Parent source, reviewed event identity or terms version is absent or changed.")
    primary, secondary = raw.get("rules_primary"), raw.get("rules_secondary")
    if not isinstance(primary, str) or not isinstance(secondary, str):
        return reject("Resolution rules must be strings.")
    matched = CPI_PRIMARY_RE.fullmatch(primary)
    if not matched or " ".join(secondary.split()) != " ".join(CPI_SECONDARY.split()):
        return reject("CPI primary/secondary rules differ from the complete reviewed template.")
    threshold_text = matched.group(1)
    threshold = _number(threshold_text)
    try:
        strike = _number(raw.get("floor_strike"))
    except SemanticValidationError:
        return reject("Invalid structured CPI strike.")
    if (raw.get("ticker") != f"KXCPI-26OCT-T{threshold_text}" or strike != threshold
            or raw.get("strike_type") != "greater"
            or raw.get("yes_sub_title") != f"Above {threshold_text}%"
            or raw.get("market_type") != "binary"
            or raw.get("cap_strike") is not None
            or raw.get("custom_strike") not in (None, {})
            or raw.get("functional_strike") not in (None, "")):
        return reject("Primary comparator, strike metadata or YES label conflicts; no title-based repair.")
    if (raw.get("close_time") != "2026-11-10T13:29:00Z"
            or raw.get("expiration_time") != "2027-02-09T14:56:00Z"
            or raw.get("latest_expiration_time") != "2027-02-09T14:56:00Z"):
        return reject("Reviewed CPI timing metadata changed; common resolution requires review.")
    p = make_cpi_settlement_target(operator="gt", threshold=float(threshold))["predicate"]
    return {
        "status": "CONDITIONAL_VERIFIED", "predicate": p, "parser": "kalshi_cpi_oct26_common_value_v1",
        "evidence": [primary, secondary], "required_model_assumptions": list(CPI_MODEL_ASSUMPTIONS),
        "source_context": {"terms_sha256": CPI_TERMS_SHA256, "terms_url": series["contract_terms_url"],
                           "settlement_sources": source, "event_ticker": event["event_ticker"]},
        "reason": "Threshold ordering is verified only under the explicitly accepted common settlement-value model. "
                  "The API and PDF exceptional-expiration clauses differ; their precedence is not established.",
    }


def parse_market_predicate(market: Mapping[str, Any]) -> dict[str, Any]:
    """Dispatch only reviewed families; all others abstain, regardless of LLM confidence."""
    metadata = market.get("metadata", {})
    raw = market.get("raw", metadata.get("raw", market) if isinstance(metadata, Mapping) else market)
    ticker = market_identifier(raw) if isinstance(raw, Mapping) else ""
    if ticker.startswith("KXCPI-"):
        return parse_kalshi_cpi_market(market)
    return parse_kalshi_fed_market(market)


def verify_relationship(target: Mapping[str, Any], market: Mapping[str, Any], proposal: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Gate an LLM proposal; only independently verified relations enter the LP.

    status CERTIFIED authorizes a relationship constraint. PROPOSED_UNVERIFIED
    never does. A parser-proved NONE remains a semantic non-match, not a failed LP.
    """
    identifier = market_identifier(market)
    result: dict[str, Any] = {"market_id": identifier, "relationship": "NONE", "status": "PROPOSED_UNVERIFIED",
                              "verification_status": "PROPOSED_UNVERIFIED", "evidence": [], "reason": "No independently verified relationship."}
    def finish(status: str, relationship: str, reason: str, evidence: list | None = None) -> dict:
        result.update(status=status, verification_status=status, relationship=relationship, reason=reason,
                      evidence=evidence or [])
        return result
    rules = resolution_rules(market)
    if proposal is not None:
        proposed = proposal.get("relationship")
        if proposed not in RELATIONSHIPS:
            return finish("INVALID_PROPOSAL", "NONE", "Invalid relationship enum.")
        if proposal.get("market_id") != identifier:
            return finish("INVALID_PROPOSAL", "NONE", "Proposal refers to an unknown or different market identifier.")
        evidence = proposal.get("evidence", [])
        if not isinstance(evidence, list) or any(not isinstance(e, str) or not e.strip() or e not in rules for e in evidence):
            return finish("INVALID_PROPOSAL", "NONE", "Evidence is not an exact substring of the actual resolution rules.")
        if proposed != "NONE" and not evidence:
            return finish("INVALID_PROPOSAL", "NONE", "A non-NONE proposal needs resolution-rule evidence.")
        result.update(proposed_relationship=proposed, proposed_explanation=str(proposal.get("explanation", "")), proposed_evidence=evidence)
    if target.get("definition_origin") == "CONTRACT_IDENTITY":
        expected_hash = hashlib.sha256(rules.encode()).hexdigest()
        if (target.get("contract_id") == identifier and target.get("venue", "kalshi") == market.get("venue", "kalshi")
                and target.get("rules_sha256") == expected_hash and rules):
            return finish("CERTIFIED", "EQUIVALENT", "Target is this exact contract's YES settlement, with identical complete rule hash.", [rules])
    if target.get("definition_origin") not in {"USER_DEFINED", "REVIEWED_REGISTRY"}:
        return finish("PROPOSED_UNVERIFIED", "NONE", "The target has no independently defined predicate. LLM-produced fields cannot certify themselves.")
    parsed = parse_market_predicate(market)
    if parsed["status"] not in {"CERTIFIED", "CONDITIONAL_VERIFIED"}:
        return finish("PROPOSED_UNVERIFIED", "NONE", parsed["reason"])
    conditional = parsed["status"] == "CONDITIONAL_VERIFIED"
    if conditional:
        required = parsed["required_model_assumptions"]
        accepted = target.get("accepted_model_assumptions", [])
        result["required_model_assumptions"] = required
        result["source_context"] = parsed["source_context"]
        if not isinstance(accepted, list) or any(a not in accepted for a in required):
            return finish("PROPOSED_UNVERIFIED", "NONE", "Unrestricted macro target not verified: "
                          "CPI settlement rules include fallback and conflicting exceptional timing. "
                          "The separate common settlement-value model has not been adopted.", parsed["evidence"])
    try:
        relation = deterministic_relation(target["predicate"], parsed["predicate"])
    except (KeyError, SemanticValidationError) as exc:
        return finish("PROPOSED_UNVERIFIED", "NONE", f"Invalid target predicate: {exc}")
    result["market_predicate"] = parsed["predicate"]
    result["deterministic_parser"] = parsed["parser"]
    if proposal and proposal.get("relationship") != relation:
        result["proposal_disagreement"] = True
    return finish("CONDITIONAL_VERIFIED" if conditional else "CERTIFIED", relation,
                  f"Independent scalar-set check: {relation}; measurement context and cancellation policy compared exactly."
                  + (" Conditional on the displayed common settlement-value assumptions." if conditional else ""), parsed["evidence"])


def parse_canonical_predicate(text: str) -> dict[str, Any] | None:
    """Parse explicitly authored JSON predicates for testing; NOT a trust gate.

    This utility never certifies a market and is not used to trust LLM extraction.
    """
    try:
        return validate_predicate(json.loads(text))
    except (json.JSONDecodeError, SemanticValidationError, TypeError):
        return None
